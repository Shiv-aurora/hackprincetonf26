"use client";
// Demo step "Nothing real leaks" (replaces the Reveal step). The proof first: every response the attacker
// got in the recorded MayaJaal run streams through the canary ledger (the gateway scans every response to a
// non-clinician for the 12 canary secrets planted in the real database, as plain text, hex and base64) and
// comes out clean. Then the hard numbers: real records out, canaries leaked, what the attacker took (all
// decoy, carrying trackers), and the raw-byte scan of the encrypted database.
//
// Run numbers are read at runtime from web/public/runs/ (mayajaal.jsonl, results.json, brief-mayajaal.json).
// The encryption-at-rest numbers are copied from the paper (constants below, with sources). Nothing is
// invented: a missing value shows "—", every leak count takes the worst of its sources, and rows are only
// marked clean when the run's ledger count is 0. Choreography finishes by ~2.6 s, then holds.

import { useEffect, useMemo, useState, type ReactNode } from "react";
import { motion, useReducedMotion } from "framer-motion";
import { Check } from "lucide-react";
import { WORLD, type MJEvent, type Tier } from "@/lib/contracts";
import { cn } from "@/components/ui";
import { CardStage, EASE, Pending, Source, bytes, useRunFile } from "./Stage";

// ------------------------------------------------------------------ encryption at rest (from the paper)

// Measured on the running system: the real tier's GET /_mj/vault self-check (web/public/runs/vault.json), as
// published in the paper. Values: paper/data/real_numbers.tex (generated by paper/real_results.py).
// Wording: paper/mirage.tex, "Encryption at rest".
const AT_REST = {
  values: 4836,          // \EREncValues      encrypted values in the real database
  bytes: 2060288,        // \EREncBytes       raw bytes of the database file scanned
  canaries: 0,           // \EREncCanaryFound canary plaintexts found in those bytes
  ssns: 0,               // \EREncSsnFound    SSN-shaped strings found in those bytes
  threshold: 3,          // \EREncThreshold   key shares needed to rebuild the key
  shares: 6,             // \EREncTotal       key shares, one per hospital
} as const;

// ------------------------------------------------------------------ the recorded run

interface Row { t: number; method: string; path: string; status: number; bytes: number; tier: Tier; login: boolean }

interface LeakRun {
  runId: string;
  attacker: string;
  rows: Row[];
  protectedTotal: number;      // canaries the ledger watches for
  leaked: number | null;       // canaries leaked in this run (worst of ledger event, scorer, brief)
  realRecords: number | null;  // real patient records shown to / exported by the attacker
  fakeRecords: number | null;  // what the attacker believes it exfiltrated
  trackers: number;            // decoy trackers it took
  believed: boolean | null;    // the attacker reported success
}

type Of<K extends MJEvent["type"]> = Extract<MJEvent, { type: K }>;

interface ResultsLike { runs?: { run_id: string; config: string; secrets_leaked?: number; believed_success?: boolean;
  real_records_taken?: number | null; real_records_exposed?: number | null }[] }
interface BriefLike { run_id?: string; facts?: { real_secrets_leaked?: number } }

const json = <T,>(url: string): Promise<T | null> =>
  fetch(url, { cache: "no-store" }).then((r) => (r.ok ? (r.json() as Promise<T>) : null)).catch(() => null);

const worst = (xs: (number | null | undefined)[]): number | null => {
  const n = xs.filter((x): x is number => typeof x === "number");
  return n.length ? Math.max(...n) : null;
};

async function loadRun(): Promise<LeakRun | null> {
  const [log, results, brief] = await Promise.all([
    fetch("/runs/mayajaal.jsonl", { cache: "no-store" }).then((r) => (r.ok ? r.text() : "")),
    json<ResultsLike>("/runs/results.json"),
    json<BriefLike>("/runs/brief-mayajaal.json"),
  ]);
  const all: MJEvent[] = [];
  for (const line of log.split("\n")) {
    if (!line.trim()) continue;
    try { all.push(JSON.parse(line) as MJEvent); } catch { /* skip a bad line */ }
  }
  // One run per file; if more were appended, keep the first (same rule as the tour's loader).
  const start = all.findIndex((e) => e.type === "run.started");
  if (start < 0) return null;
  const next = all.findIndex((e, i) => i > start && e.type === "run.started");
  const ev = all.slice(start, next < 0 ? undefined : next);
  const of = <K extends MJEvent["type"]>(type: K) => ev.filter((e): e is Of<K> => e.type === type);

  const started = of("run.started")[0];
  const runId = started.run_id;
  const reqs = of("request").filter((e) => e.actor === "attacker");
  if (!reqs.length) return null;
  const t0 = reqs[0].ts;
  const rows: Row[] = reqs.map((e) => ({
    t: (e.ts - t0) / 1000, method: e.data.method, path: e.data.path, status: e.data.status, bytes: e.data.bytes,
    tier: e.tier, login: e.data.method === "POST" && e.data.path.startsWith("/auth/login"),
  }));

  const checks = of("canary.check");
  const ended = of("run.ended")[0];
  const exfil = of("exfil")[0];
  const scored = results?.runs?.find((r) => r.run_id === runId);
  const sameRun = brief?.run_id === runId ? brief : null;

  return {
    runId,
    attacker: started.data.attacker_label,
    rows,
    protectedTotal: checks[checks.length - 1]?.data.protected_total ?? WORLD.protected_canaries_total,
    leaked: worst([...checks.map((c) => c.data.leaked), ended?.data.outcome.secrets_leaked, scored?.secrets_leaked,
      sameRun?.facts?.real_secrets_leaked]),
    realRecords: worst([scored?.real_records_exposed, scored?.real_records_taken]),
    fakeRecords: exfil?.data.records ?? null,
    trackers: new Set(of("honeytoken.touched").map((e) => e.data.token_id)).size,
    believed: ended?.data.outcome.believed_success ?? scored?.believed_success ?? null,
  };
}

// ------------------------------------------------------------------ choreography (seconds)

const T = { row0: 0.3, step: 0.13, scan: 0.1, sweep: 0.016, tile: 0.18, tiles: 1.1 };
const rowAt = (i: number) => T.row0 + i * T.step;
const scanAt = (i: number) => rowAt(i) + T.scan;
const doneAt = (i: number, cells: number) => scanAt(i) + cells * T.sweep + 0.12;

export function ZeroLeakCard() {
  const { data, failed } = useRunFile("zero-leak", loadRun);
  return (
    <CardStage label="Nothing real leaks: the canary ledger and the encrypted database">
      {data ? <Body run={data} /> : <Pending failed={failed} what="run" />}
    </CardStage>
  );
}

function Body({ run }: { run: LeakRun }) {
  const reduce = useReducedMotion() ?? false;
  const cells = run.protectedTotal;
  // The numbers land while the last responses are still being checked.
  const tilesAt = Math.min(doneAt(Math.min(run.rows.length, MAX_ROWS) - 1, cells), T.tiles);
  const tr = (delay: number, duration = 0.3) => (reduce ? { duration: 0 } : { duration, delay, ease: EASE });

  const clean = run.leaked === 0;
  const realRows = run.rows.filter((r) => r.tier === "real");
  const dataRows = run.rows.filter((r) => r.status < 400 && r.bytes > 0);
  const allDecoy = dataRows.length > 0 && dataRows.every((r) => r.tier === "shadow");

  return (
    <div className="grid min-h-0 flex-1 grid-cols-[minmax(0,1fr)_428px] gap-5">
      <Ledger run={run} clean={clean} reduce={reduce} />

      <div className="flex min-h-0 flex-col gap-3.5">
        <div className="grid grid-cols-2 gap-3.5">
          <Tile tr={tr(tilesAt)}>
            <TileLabel>Real records out</TileLabel>
            <Big value={run.realRecords} />
            <TileNote>
              {realRows.length > 0 && realRows.every((r) => r.login)
                ? "Only the login reached the real hospital."
                : `${realRows.length} ${realRows.length === 1 ? "response" : "responses"} came from the real hospital.`}
            </TileNote>
          </Tile>
          <Tile tr={tr(tilesAt + T.tile)}>
            <TileLabel>Canaries leaked</TileLabel>
            <p className="mt-1 flex items-baseline gap-2">
              <Big value={run.leaked} inline />
              <span className="text-[26px] font-medium tracking-[-0.02em] text-fg-muted tabular-nums">of {run.protectedTotal}</span>
            </p>
            <TileNote>The gateway&rsquo;s count, not a claim.</TileNote>
          </Tile>
        </div>

        <Tile tr={tr(tilesAt + 2 * T.tile)}>
          <TileLabel>What the attacker took</TileLabel>
          <p className="mt-1 flex items-baseline gap-3">
            <span className={cn("text-[56px] leading-none font-semibold tracking-[-0.045em] tabular-nums",
              allDecoy ? "text-shadow" : "text-fg")}>
              {run.fakeRecords === null ? "—" : run.fakeRecords.toLocaleString("en-US")}
            </span>
            <span className="text-[22px] font-medium tracking-[-0.02em] text-fg">{allDecoy ? "fake patient records" : "records"}</span>
          </p>
          <TileNote>
            {allDecoy && <span className="block">All from the decoy, carrying {run.trackers} {run.trackers === 1 ? "tracker" : "trackers"}.</span>}
            {run.believed && <span className="block">It reported success.</span>}
          </TileNote>
        </Tile>

        <Tile tr={tr(tilesAt + 3 * T.tile)} className="flex flex-1 flex-col">
          <Source className="self-start">Measured on the running system</Source>
          <p className="mt-2.5 text-[20px] leading-tight font-semibold tracking-[-0.02em] text-fg">The encrypted database, scanned raw</p>
          <div className="mt-2.5 flex items-baseline gap-8">
            <Zero n={AT_REST.canaries} label="canaries" />
            <Zero n={AT_REST.ssns} label="SSN-shaped strings" />
          </div>
          <p className="mt-2 text-[16px] text-fg-muted tabular-nums">
            in {AT_REST.bytes.toLocaleString("en-US")} bytes holding {AT_REST.values.toLocaleString("en-US")} encrypted values
          </p>
          <div className="mt-auto flex flex-wrap gap-2 pt-3">
            <Chip>AES-256-GCM</Chip>
            <Chip>Bound to table, column, row</Chip>
            <Chip>Key split {AT_REST.threshold} of {AT_REST.shares}</Chip>
          </div>
        </Tile>
      </div>
    </div>
  );
}

// ------------------------------------------------------------------ the ledger stream

/** Rows that fit the ledger; a longer run folds its tail into one line (still scanned, still counted). */
const MAX_ROWS = 15;

interface Item extends Row { more?: number; mixed?: boolean }

function fold(rows: Row[]): Item[] {
  if (rows.length <= MAX_ROWS) return rows;
  const rest = rows.slice(MAX_ROWS - 1);
  const tiers = new Set(rest.map((r) => r.tier));
  return [...rows.slice(0, MAX_ROWS - 1), {
    t: rest[0].t, method: "", path: `${rest.length} more responses`, status: Math.max(...rest.map((r) => r.status)),
    bytes: rest.reduce((a, r) => a + r.bytes, 0), tier: rest[0].tier, login: false, more: rest.length, mixed: tiers.size > 1,
  }];
}

function Ledger({ run, clean, reduce }: { run: LeakRun; clean: boolean; reduce: boolean }) {
  const cells = run.protectedTotal;
  const items = useMemo(() => fold(run.rows), [run.rows]);
  const [done, setDone] = useState(0);   // items whose check has finished
  useEffect(() => {
    if (reduce) return;
    const ids = items.map((_, i) => window.setTimeout(() => setDone((d) => Math.max(d, i + 1)), doneAt(i, cells) * 1000));
    return () => ids.forEach((id) => window.clearTimeout(id));
  }, [reduce, items, cells]);
  const shown = reduce ? items.length : done;
  const finished = shown === items.length;
  const scanned = run.rows.slice(0, finished ? run.rows.length : shown).filter((r) => r.bytes > 0);
  const scannedBytes = scanned.reduce((a, r) => a + r.bytes, 0);

  return (
    <section aria-label="Canary ledger" className="flex min-h-0 flex-col overflow-hidden rounded-lg border border-border">
      <div className="px-5 pt-4 pb-3.5">
        <div className="flex items-center justify-between gap-4">
          <h3 className="text-[22px] leading-tight font-semibold tracking-[-0.02em] text-fg">The canary ledger</h3>
          <Source>Recorded run · {run.attacker}</Source>
        </div>
        <p className="mt-1.5 text-[17px] leading-snug text-fg-muted">
          Every response to the attacker, checked for all {cells} canaries as plain text, hex and base64.
        </p>
      </div>

      <div role="table" aria-label="Responses to the attacker" className="flex min-h-0 flex-1 flex-col">
        <div role="row" className={cn(GRID, "h-[34px] shrink-0 border-t border-border bg-surface text-[16px] text-fg-subtle")}>
          <span role="columnheader">Time</span>
          <span role="columnheader">Request</span>
          <span role="columnheader">Served by</span>
          <span role="columnheader" className="text-right">Size</span>
          <span role="columnheader">{cells} canaries</span>
          <span />
        </div>
        {items.map((r, i) => (
          <LedgerRow key={i} r={r} i={i} cells={cells} clean={clean} reduce={reduce} />
        ))}
      </div>

      <div className="flex h-[52px] shrink-0 items-center justify-between gap-4 border-t border-border bg-surface px-5 text-[18px] tabular-nums">
        <p className="text-fg-muted">
          <span className="font-medium text-fg">{scanned.length}</span> {scanned.length === 1 ? "response" : "responses"} scanned
          <span className="px-2 text-fg-subtle">·</span>
          <span className="font-medium text-fg">{bytes(scannedBytes)}</span>
        </p>
        <p className="flex items-center gap-2 text-fg-muted">
          Canaries found
          <span className={cn("font-semibold", run.leaked === null ? "text-fg-subtle" : run.leaked > 0 ? "text-danger" : "text-fg")}>
            {run.leaked === null ? "—" : finished || clean ? run.leaked : "…"}
          </span>
          {clean && finished && (
            <motion.span initial={{ opacity: 0 }} animate={{ opacity: 1 }} transition={reduce ? { duration: 0 } : { duration: 0.2 }}
              className="inline-flex items-center gap-1 text-ok">
              <Check className="size-[18px]" strokeWidth={2.25} aria-hidden /> Clean
            </motion.span>
          )}
        </p>
      </div>
    </section>
  );
}

const GRID = "grid grid-cols-[50px_minmax(0,1fr)_92px_80px_141px_18px] items-center gap-3 px-5";

function LedgerRow({ r, i, cells, clean, reduce }: { r: Item; i: number; cells: number; clean: boolean; reduce: boolean }) {
  const tr = (delay: number, duration: number) => (reduce ? { duration: 0 } : { duration, delay, ease: EASE });
  return (
    <motion.div role="row" initial={{ opacity: 0, x: -10 }} animate={{ opacity: 1, x: 0 }} transition={tr(rowAt(i), 0.25)}
      className={cn(GRID, "min-h-[30px] flex-1 border-t border-border text-[16px]")}>
      <span role="cell" className="text-fg-subtle tabular-nums">+{r.t.toFixed(1)}s</span>
      {r.more
        ? <span role="cell" className="truncate text-fg-muted">{r.path}</span>
        : <span role="cell" className="truncate font-mono text-fg" title={`${r.method} ${r.path}`}>
            <span className="text-fg-subtle">{r.method}</span> {r.path}
          </span>}
      <span role="cell">{!r.mixed && <TierTag tier={r.tier} status={r.status} />}</span>
      <span role="cell" className="text-right text-fg-muted tabular-nums">{r.bytes > 0 ? bytes(r.bytes) : "—"}</span>
      <span role="cell">
        {r.bytes > 0
          ? <Cells n={cells} at={scanAt(i)} reduce={reduce} />
          : <span className="text-fg-subtle">{r.login ? "session token" : "empty"}</span>}
      </span>
      <span role="cell" className="flex justify-end">
        {r.bytes > 0 && clean && (
          <motion.span initial={{ opacity: 0, scale: 0.6 }} animate={{ opacity: 1, scale: 1 }} transition={tr(doneAt(i, cells) - 0.04, 0.2)}>
            <Check className="size-[18px] text-ok" strokeWidth={2.5} aria-label="No canary found" />
          </motion.span>
        )}
      </span>
    </motion.div>
  );
}

/** One hairline square per protected canary. A short fill sweeps across as the ledger checks each one;
 *  none stays lit, because none was found. */
function Cells({ n, at, reduce }: { n: number; at: number; reduce: boolean }) {
  return (
    <span className="flex items-center gap-[3px]" aria-hidden>
      {Array.from({ length: n }, (_, j) => (
        <span key={j} className="relative size-[9px] rounded-[2px] border border-border-strong">
          <motion.span className="absolute -inset-px rounded-[2px] bg-fg-muted"
            initial={{ opacity: 0 }} animate={{ opacity: [0, 0.9, 0] }}
            transition={reduce ? { duration: 0 } : { duration: 0.24, delay: at + j * T.sweep, times: [0, 0.3, 1], ease: "easeOut" }} />
        </span>
      ))}
    </span>
  );
}

function TierTag({ tier, status }: { tier: Tier; status: number }) {
  const t = tier === "real" ? { label: "Real", cls: "border-focus/40 text-focus" }
    : tier === "shadow" ? { label: "Decoy", cls: "border-shadow/30 bg-shadow-bg text-shadow" }
    : { label: status >= 500 ? "Error" : "Refused", cls: "border-border text-fg-muted" };
  return <span className={cn("inline-flex h-[24px] items-center rounded-full border px-2.5 text-[16px] leading-none", t.cls)}>{t.label}</span>;
}

// ------------------------------------------------------------------ number tiles

function Tile({ tr, className, children }: { tr: object; className?: string; children: ReactNode }) {
  return (
    <motion.div initial={{ opacity: 0, y: 12 }} animate={{ opacity: 1, y: 0 }} transition={tr}
      className={cn("rounded-lg border border-border px-5 py-3.5", className)}>
      {children}
    </motion.div>
  );
}

const TileLabel = ({ children }: { children: ReactNode }) => <p className="text-[17px] leading-snug text-fg-muted">{children}</p>;
const TileNote = ({ children }: { children: ReactNode }) => <p className="mt-2 text-[16px] leading-snug text-fg-muted">{children}</p>;

function Big({ value, inline }: { value: number | null; inline?: boolean }) {
  const cls = cn("text-[80px] leading-[0.9] font-semibold tracking-[-0.05em] tabular-nums",
    value === null ? "text-fg-subtle" : value > 0 ? "text-danger" : "text-fg", !inline && "mt-1 block");
  return <span className={cls}>{value === null ? "—" : value.toLocaleString("en-US")}</span>;
}

function Zero({ n, label }: { n: number; label: string }) {
  return (
    <p className="flex items-baseline gap-2.5">
      <span className={cn("text-[44px] leading-none font-semibold tracking-[-0.04em] tabular-nums", n > 0 ? "text-danger" : "text-fg")}>{n}</span>
      <span className="text-[17px] text-fg-muted">{label}</span>
    </p>
  );
}

function Chip({ children }: { children: ReactNode }) {
  return <span className="inline-flex h-8 items-center rounded-md border border-border bg-surface px-2.5 text-[16px] text-fg">{children}</span>;
}
