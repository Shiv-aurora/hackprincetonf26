"""Extended MIRAGE evaluation with 95% confidence intervals, for the paper. SIMULATION ONLY.

    cd backend && uv run python ../paper/eval_ci.py [--seeds 2000]

Re-uses mayajaal.mirage.evaluate.run_session unchanged (same simulated attacker, same seeding, same
common-random-numbers design) and only adds more seeds and interval estimates. Writes:

    paper/data/eval_ci.json        all per-goal / per-strategy estimates with 95% CIs
    paper/data/steps_by_goal.dat   pgfplots table: mean steps to P(true goal) > 0.8 by goal (matched)
    paper/data/numbers.tex         \\newcommand macros used by mirage.tex (no hand-copied numbers)

The macros also carry the committed 500-seed results from backend/mayajaal/mirage/eval_results.json.
"""

from __future__ import annotations

import argparse
import json
import math
import statistics
from pathlib import Path

from mayajaal.mirage.evaluate import GOALS, OUT_PATH, STRATEGIES, VARIANTS, run_session

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
Z = 1.959964
ATTACK = [g for g in GOALS if g != "benign"]
VTAG = {"matched": "M", "misspecified": "X"}
STAG = {"mirage": "Mirage", "random": "Random", "none": "None"}


def mean_ci(xs: list[float]) -> tuple[float, float]:
    """Mean and 95% half-width (normal approximation)."""
    return statistics.fmean(xs), Z * statistics.stdev(xs) / math.sqrt(len(xs))


def strat_ci(per_goal: dict[str, list[float]]) -> tuple[float, float]:
    """Equal-weight average over goals with a stratified 95% half-width."""
    k = len(per_goal)
    m = statistics.fmean(statistics.fmean(v) for v in per_goal.values())
    var = sum(statistics.variance(v) / len(v) for v in per_goal.values()) / k ** 2
    return m, Z * math.sqrt(var)


def pm(mc: tuple[float, float], scale: float = 1.0, digits: int = 2) -> str:
    s = f"{scale * mc[0]:.{digits}f}".replace("-", "\\ensuremath{-}")
    return f"{s}\\,$\\pm$\\,{scale * mc[1]:.{digits}f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=2000)
    ap.add_argument("--steps", type=int, default=30)
    args = ap.parse_args()
    n, T = args.seeds, args.steps

    raw: dict = {v: {g: {s: [run_session(g, seed, s, v, T) for seed in range(n)] for s in STRATEGIES}
                     for g in GOALS} for v in VARIANTS}

    def steps(r) -> float:      # censored at T, as in evaluate.py
        return float(r["steps_to_confident"] if r["steps_to_confident"] is not None else T)

    metrics = {
        "steps": steps,
        "reached": lambda r: float(r["steps_to_confident"] is not None),
        "acc10": lambda r: float(r["correct_at_10"]),
        "diverted": lambda r: float(r["diverted"]),
        "crumbs": lambda r: float(len(r["breadcrumbs"])),
    }
    main_m = ("steps", "reached", "acc10")
    out: dict = {"label": "Simulation of our own model (hand-written likelihoods), not a measurement of real "
                          "attackers. 95% CIs, normal approximation; attack averages are equal-weight over the "
                          "four attack goals with stratified variance; differences are paired by seed.",
                 "seeds_per_cell": n, "max_steps": T, "per_goal": {}, "attack_avg": {}, "paired_diff": {}}
    for v in VARIANTS:
        out["per_goal"][v] = {g: {s: {m: mean_ci([f(r) for r in raw[v][g][s]]) for m, f in metrics.items()}
                                  for s in STRATEGIES} for g in GOALS}
        out["attack_avg"][v] = {s: {m: strat_ci({g: [metrics[m](r) for r in raw[v][g][s]] for g in ATTACK})
                                    for m in main_m} for s in STRATEGIES}
        out["paired_diff"][v] = {}
        for a, b in (("mirage", "none"), ("mirage", "random"), ("random", "none")):
            out["paired_diff"][v][f"{a}-{b}"] = {
                m: strat_ci({g: [metrics[m](x) - metrics[m](y) for x, y in zip(raw[v][g][a], raw[v][g][b])]
                             for g in ATTACK}) for m in main_m}

    DATA.mkdir(exist_ok=True)
    (DATA / "eval_ci.json").write_text(json.dumps(out, indent=2) + "\n")

    lines = ["goal idx " + " ".join(f"{s} {s}ci" for s in STRATEGIES)]
    for i, g in enumerate(ATTACK):
        cells = " ".join(f"{out['per_goal']['matched'][g][s]['steps'][0]:.3f} "
                         f"{out['per_goal']['matched'][g][s]['steps'][1]:.3f}" for s in STRATEGIES)
        lines.append(f"{g} {i} {cells}")
    (DATA / "steps_by_goal.dat").write_text("\n".join(lines) + "\n")

    committed = json.loads(OUT_PATH.read_text())
    mac = ["% generated by paper/eval_ci.py -- do not edit by hand",
           f"\\newcommand{{\\NSeedsCI}}{{{n:,}}}".replace(",", "{,}", 1) if n >= 1000 else
           f"\\newcommand{{\\NSeedsCI}}{{{n}}}",
           f"\\newcommand{{\\NSeedsCommitted}}{{{committed['seeds_per_cell']}}}",
           f"\\newcommand{{\\MaxSteps}}{{{T}}}"]
    for v in VARIANTS:
        cs = committed["summary_attack_goals"][v]
        for s in STRATEGIES:
            p = f"{VTAG[v]}{STAG[s]}"
            mac += [f"\\newcommand{{\\C{p}Steps}}{{{cs[s]['mean_steps_to_0.8']:.2f}}}",
                    f"\\newcommand{{\\C{p}Reach}}{{{100 * cs[s]['reached_0.8']:.1f}}}",
                    f"\\newcommand{{\\C{p}Acc}}{{{100 * cs[s]['accuracy_at_10']:.1f}}}"]
            a = out["attack_avg"][v][s]
            mac += [f"\\newcommand{{\\E{p}Steps}}{{{pm(a['steps'])}}}",
                    f"\\newcommand{{\\E{p}Reach}}{{{pm(a['reached'], 100, 1)}}}",
                    f"\\newcommand{{\\E{p}Acc}}{{{pm(a['acc10'], 100, 1)}}}"]
        for pair, pn in (("mirage-none", "MvN"), ("mirage-random", "MvR"), ("random-none", "RvN")):
            d = out["paired_diff"][v][pair]
            mac += [f"\\newcommand{{\\D{VTAG[v]}{pn}Steps}}{{{pm(d['steps'])}}}",
                    f"\\newcommand{{\\D{VTAG[v]}{pn}Reach}}{{{pm(d['reached'], 100, 1)}}}",
                    f"\\newcommand{{\\D{VTAG[v]}{pn}Acc}}{{{pm(d['acc10'], 100, 1)}}}"]
        b = out["per_goal"][v]["benign"]["mirage"]
        mac += [f"\\newcommand{{\\E{VTAG[v]}BenignDiv}}{{{pm(b['diverted'], 100, 1)}}}",
                f"\\newcommand{{\\E{VTAG[v]}BenignCrumbs}}{{{b['crumbs'][0]:.3f}}}"]
    cb = committed["results"]["matched"]["benign"]["mirage"]
    mac += [f"\\newcommand{{\\CMBenignDiv}}{{{100 * cb['diverted']:.1f}}}",
            f"\\newcommand{{\\CMBenignCrumbs}}{{{cb['breadcrumbs_per_session']:.2f}}}"]
    for g in ATTACK:
        cg = committed["results"]["matched"][g]
        mac += [f"\\newcommand{{\\CMIG{g.capitalize()}}}{{{cg['mirage']['mean_info_gain_bits']:.3f}}}",
                f"\\newcommand{{\\CRIG{g.capitalize()}}}{{{cg['random']['mean_info_gain_bits']:.3f}}}",
                f"\\newcommand{{\\CMSteps{g.capitalize()}}}{{{cg['mirage']['mean_steps_to_0.8']:.2f}}}",
                f"\\newcommand{{\\CNSteps{g.capitalize()}}}{{{cg['none']['mean_steps_to_0.8']:.2f}}}",
                f"\\newcommand{{\\CMReach{g.capitalize()}}}{{{100 * cg['mirage']['reached_0.8']:.1f}}}",
                f"\\newcommand{{\\CNReach{g.capitalize()}}}{{{100 * cg['none']['reached_0.8']:.1f}}}"]
    (DATA / "numbers.tex").write_text("\n".join(mac) + "\n")
    print(json.dumps({v: out["attack_avg"][v] for v in VARIANTS}, indent=1))
    print(json.dumps(out["paired_diff"], indent=1))
    print(json.dumps({v: out["per_goal"][v]["benign"]["mirage"] for v in VARIANTS}, indent=1))


if __name__ == "__main__":
    main()
