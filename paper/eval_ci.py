"""Numbers for the MIRAGE paper, with 95% confidence intervals. SIMULATION ONLY.

    cd backend && uv run python ../paper/eval_ci.py            # from the committed results file
    cd backend && uv run python ../paper/eval_ci.py --rerun    # rerun the harness first (2,000 seeds)

Source of every number: backend/mayajaal/mirage/eval_planners.json, written by
`python -m mayajaal.mirage.evaluate_planners` (one harness, paired seeds, all strategies). This script
only formats it. Writes:

    paper/data/eval_ci.json        copy of the summary the macros were built from
    paper/data/steps_by_goal.dat   pgfplots table: steps to P(true goal) > 0.8 by goal (matched, cautious)
    paper/data/numbers.tex         \\newcommand macros used by mirage.tex (no hand-copied numbers)

Macro names: \\R<variant><attacker><strategy><metric> is "mean +- 95% half-width";
\\D<variant><attacker><strategy><metric> is the paired difference to the previous planner (IgOne).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from mayajaal.mirage import evaluate_planners as ep

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
VTAG = {"matched": "M", "misspecified": "X"}
ATAG = {"bold": "Bold", "cautious": "Caut", "cautious_shifted": "Shift", "mixed": "Mix"}
STAG = {"none": "None", "random": "Random", "ig1": "IgOne", "ig_fast": "IgFast", "lookahead": "Look",
        "stealth1": "StealthOne", "stealth": "Stealth", "stealth_robust": "Robust"}
# metric -> (macro suffix, scale, digits)
MTAG = {"steps": ("Steps", 1.0, 2), "identified": ("Ident", 100.0, 1), "final_correct": ("Acc", 100.0, 1),
        "engagement": ("Stay", 1.0, 1), "left": ("Left", 100.0, 1), "lures": ("Lures", 1.0, 2),
        "claim_wrong": ("Wrong", 100.0, 1)}


def pm(mc: list[float], scale: float = 1.0, digits: int = 2, signed: bool = False) -> str:
    m = f"{scale * mc[0]:{'+' if signed else ''}.{digits}f}".replace("-", "\\ensuremath{-}")
    return f"{m}\\,$\\pm$\\,{scale * mc[1]:.{digits}f}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--rerun", action="store_true")
    ap.add_argument("--seeds", type=int, default=2000)
    args = ap.parse_args()
    if args.rerun:
        ep.main(["--seeds", str(args.seeds)])
    data = json.loads(ep.OUT_PATH.read_text())
    summary = data["summary"]

    lines = ["% Generated by paper/eval_ci.py from backend/mayajaal/mirage/eval_planners.json. Do not edit.",
             f"% {data['label']}"]

    def macro(name: str, value: str) -> None:
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    macro("NSeeds", f"{data['seeds_per_cell']:,}".replace(",", "{,}"))
    macro("MaxSteps", str(data["max_steps"]))
    for v, vt in VTAG.items():
        for a, at in ATAG.items():
            for s, stg in STAG.items():
                cell = summary[v][a][s]
                for metric, (mt, scale, digits) in MTAG.items():
                    macro(f"R{vt}{at}{stg}{mt}", pm(cell[metric], scale, digits))
                    d = cell.get(f"{metric}_vs_ig1")
                    if d is not None:
                        macro(f"D{vt}{at}{stg}{mt}", pm(d, scale, digits, signed=True))
        b = summary[v]["benign"]["stealth"]
        macro(f"R{vt}BenignDiv", pm(b["false_diversion"], 100.0, 1))
        macro(f"R{vt}BenignLures", f"{b['lures_per_session']:.2f}")

    rows = ["idx goal none nonec ig1 ig1c stealth stealthc"]
    for i, g in enumerate(ep.ATTACK):
        cells = [summary["matched"]["cautious"][s]["by_goal_steps"][g] for s in ("none", "ig1", "stealth")]
        rows.append(f"{i} {g} " + " ".join(f"{m:.3f} {c:.3f}" for m, c in cells))

    DATA.mkdir(exist_ok=True)
    (DATA / "numbers.tex").write_text("\n".join(lines) + "\n")
    (DATA / "steps_by_goal.dat").write_text("\n".join(rows) + "\n")
    (DATA / "eval_ci.json").write_text(json.dumps(
        {k: data[k] for k in ("label", "seeds_per_cell", "max_steps", "ci", "baseline", "summary")}, indent=1) + "\n")
    print(f"wrote {len(lines) - 2} macros from {ep.OUT_PATH}")


if __name__ == "__main__":
    main()
