"""Write paper/data/real_numbers.tex from the runs recorded on the running system.

Sources (all produced by the running stack, none typed by hand):
  web/public/runs/results.json      scripts/record_runs.py: same scripted attack under baseline/static/mayajaal
  web/public/runs/mayajaal.jsonl    the MayaJaal run's event log (trackers planted / taken)
  web/public/runs/vault.json        GET /_mj/vault on the real tier (encryption at rest self-check)

    python3 paper/real_results.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "web" / "public" / "runs"
OUT = ROOT / "paper" / "data" / "real_numbers.tex"


def num(n: int | float) -> str:
    return f"{int(n):,}".replace(",", "{,}")


def main() -> None:
    res = json.loads((RUNS / "results.json").read_text())
    rows = {r["config"]: r for r in res["runs"]}
    events = [json.loads(l) for l in (RUNS / "mayajaal.jsonl").read_text().splitlines() if l.strip()]
    vault = json.loads((RUNS / "vault.json").read_text())

    planted = {e["data"]["path"] for e in events if e["type"] == "breadcrumb.planted"}
    planted |= {e["data"]["placed_at"] for e in events if e["type"] == "honeytoken.minted"}
    taken = {e["data"]["where"] for e in events if e["type"] == "honeytoken.touched"}
    planted |= taken   # session honeytokens placed when the decoy is generated emit no event until touched
    requests = sum(1 for e in events if e["type"] == "request" and e.get("actor") == "attacker")

    enc_values = sum(f["encrypted_rows"] for f in vault["encrypted_fields"])
    sc = vault["self_check"]
    shares = vault["shares"]

    def row(c: str) -> dict:
        return rows[c]

    macros = {
        "ERBaseReal": num(row("baseline")["real_records_taken"]),
        "ERStaticReal": num(row("static")["real_records_taken"]),
        "ERMjReal": num(row("mayajaal")["real_records_taken"]),
        "ERBaseLeak": num(row("baseline")["secrets_leaked"]),
        "ERStaticLeak": num(row("static")["secrets_leaked"]),
        "ERMjLeak": num(row("mayajaal")["secrets_leaked"]),
        "ERStaticOverlap": f"{round(row('static')['decoy_overlap_between_sessions'] * 100)}\\%",
        "ERMjOverlap": f"{round(row('mayajaal')['decoy_overlap_between_sessions'] * 100)}\\%",
        "ERStaticDivert": f"{row('static')['time_to_divert_s']:.1f}",
        "ERMjDivert": f"{row('mayajaal')['time_to_divert_s']:.1f}",
        "ERBelieved": f"{sum(1 for r in rows.values() if r['believed_success'])} of {len(rows)}",
        "ERMjRequests": num(requests),
        "ERMjPlanted": num(len(planted)),
        "ERMjTaken": num(len(taken)),
        "ERMjFake": num(next((e["data"]["records"] for e in events if e["type"] == "exfil"), 0)),
        "EREncValues": num(enc_values),
        "EREncBytes": num(sc["bytes_scanned"]),
        "EREncCanaryFound": num(sc["canary_plaintexts_found"]),
        "EREncSsnFound": num(sc["ssn_like_strings_found"]),
        "EREncThreshold": str(shares["threshold"]),
        "EREncTotal": str(shares["total"]),
    }
    lines = ["% Generated by paper/real_results.py from web/public/runs/ (recorded on the running system). Do not edit.",
             "% One run per configuration with a fixed scripted attacker; not red-team data."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    OUT.write_text("\n".join(lines) + "\n")
    print(OUT.read_text())


if __name__ == "__main__":
    main()
